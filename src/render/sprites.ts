export type MaskOptions = { alpha?: number; flip?: 1 | -1 };

export function drawMask(
  ctx: CanvasRenderingContext2D,
  mask: Mask,
  palette: MaskPalette,
  x: number,
  y: number,
  scale = 1,
  opts: MaskOptions = {},
): void {
  if (opts.alpha !== undefined) ctx.globalAlpha = opts.alpha;
  for (let ry = 0; ry < mask.length; ry++) {
    const row = mask[ry];
    let rx = 0;
    while (rx < row.length) {
      const ch = row[rx];
      if (ch === "0" || !(ch in palette) || !palette[ch]) {
        rx++;
        continue;
      }
      let run = 1;
      while (rx + run < row.length && row[rx + run] === ch) run++;
      const col = palette[ch]!;
      ctx.fillStyle = `rgb(${col[0]},${col[1]},${col[2]})`;
      const dx = opts.flip === -1 ? x + (row.length - rx - run) * scale : x + rx * scale;
      ctx.fillRect(dx, y + ry * scale, run * scale, scale);
      rx += run;
    }
  }
  if (opts.alpha !== undefined) ctx.globalAlpha = 1;
}

/** Падающий «предмет-улика»: папка дела. */
export function drawFolder(
  ctx: CanvasRenderingContext2D,
  pal: Palette,
  x: number,
  y: number,
  kind: "folder" | "gold" | "evil",
): void {
  const body = kind === "evil" ? pal.red : kind === "gold" ? pal.goldHi : pal.paper;
  const shadow = kind === "evil" ? pal.redLo : kind === "gold" ? pal.goldLo : pal.dim;
  ctx.fillStyle = `rgb(${body[0]},${body[1]},${body[2]})`;
  ctx.fillRect(x + 1, y, 5, 2); // язычок папки
  ctx.fillRect(x + 2, y + 1, 9, 1);
  ctx.fillRect(x + 4, y + 2, 3, 1);
  ctx.fillRect(x, y + 2, 13, 6);
  ctx.fillStyle = `rgb(${shadow[0]},${shadow[1]},${shadow[2]})`;
  ctx.fillRect(x, y + 7, 13, 1);
  ctx.fillRect(x + 12, y + 2, 1, 6);
  if (kind === "evil") {
    // мини-ухмылка на папке
    ctx.fillStyle = "#0d0a20";
    ctx.fillRect(x + 3, y + 4, 2, 1);
    ctx.fillRect(x + 8, y + 4, 2, 1);
    ctx.fillRect(x + 4, y + 6, 5, 1);
  } else {
    ctx.fillStyle = `rgb(${shadow[0]},${shadow[1]},${shadow[2]})`;
    ctx.fillRect(x + 3, y + 4, 6, 1);
    ctx.fillRect(x + 3, y + 5, 4, 1);
    ctx.fillStyle = `rgb(${pal.red[0]},${pal.red[1]},${pal.red[2]})`;
    ctx.fillRect(x + 2, y + 3, 1, 3);
  }
}

/** Ухмылка Кровавого Джона — рисуется процедурно (сглаживание по нашей пиксельной сетке). */
export function drawGrin(ctx: CanvasRenderingContext2D, x: number, y: number, pal: Palette, s: number): void {
  const cx = Math.round(x + 16 * s);
  const cy = Math.round(y + 15 * s);
  const R = Math.round(14 * s);
  const put = (col: readonly [number, number, number], rx: number, ry: number, rw: number, rh: number) => {
    ctx.fillStyle = `rgb(${col[0]},${col[1]},${col[2]})`;
    ctx.fillRect(x + Math.round(rx * s), y + Math.round(ry * s), Math.round(rw * s), Math.round(rh * s));
  };
  // брызги
  put(pal.blood, -1, 8, 2, 5);
  put(pal.blood, 30, 16, 2, 4);
  put(pal.blood, 25, 3, 2, 3);
  // тело
  ctx.fillStyle = `rgb(${pal.red[0]},${pal.red[1]},${pal.red[2]})`;
  ctx.beginPath();
  ctx.ellipse(cx, cy, R, Math.round(R * 0.96), 0, 0, Math.PI * 2);
  ctx.fill();
  // тень снизу
  ctx.fillStyle = `rgb(${pal.redLo[0]},${pal.redLo[1]},${pal.redLo[2]})`;
  ctx.beginPath();
  ctx.ellipse(cx, cy + Math.round(R * 0.36), Math.round(R * 0.9), Math.round(R * 0.42), 0, 0, Math.PI);
  ctx.fill();
  // свет сверху-слева
  ctx.fillStyle = `rgb(${pal.redHi[0]},${pal.redHi[1]},${pal.redHi[2]})`;
  ctx.fillRect(cx - Math.round(R * 0.72), cy - Math.round(R * 0.8), Math.round(R * 0.36), Math.max(1, Math.round(s)));
  // глаза
  put(pal.ink, 9, 9, 4, 5);
  put(pal.ink, 19, 9, 4, 5);
  // улыбка
  ctx.strokeStyle = `rgb(${pal.ink[0]},${pal.ink[1]},${pal.ink[2]})`;
  ctx.lineWidth = Math.max(1, Math.round(1.4 * s));
  ctx.beginPath();
  ctx.arc(cx, cy - Math.round(2 * s), Math.round(8.5 * s), 0.3, Math.PI - 0.3);
  ctx.stroke();
  // капли крови с «улыбки»
  put(pal.blood, 7, 24, 1, 4);
  put(pal.blood, 14, 26, 1, 3);
  put(pal.blood, 22, 24, 1, 4);
  // шрам через лицо
  put(pal.blood, 4, 7, 1, 3);
  put(pal.blood, 5, 10, 1, 2);
}

